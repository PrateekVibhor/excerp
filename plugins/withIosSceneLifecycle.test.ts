import * as fs from 'fs';
import * as path from 'path';

// eslint-disable-next-line @typescript-eslint/no-require-imports
const plugin = require('./withIosSceneLifecycle');
const { classifyAppDelegate, patchAppDelegate, addSceneManifest, SCENE_MANIFEST } = plugin.helpers;

const classic = fs.readFileSync(path.join(__dirname, '__fixtures__/AppDelegate.sdk57.swift'), 'utf8'); // as generated by SDK 57
const adopted = fs.readFileSync(path.join(__dirname, 'ios-scene-lifecycle/AppDelegate.swift'), 'utf8');
const sceneDelegate = fs.readFileSync(path.join(__dirname, 'ios-scene-lifecycle/SceneDelegate.swift'), 'utf8');

describe('classifyAppDelegate', () => {
  it('recognises the SDK 57 template as classic', () => {
    expect(classifyAppDelegate(classic)).toBe('classic');
  });

  it('recognises an AppDelegate that already provides the factory to a scene', () => {
    expect(classifyAppDelegate(adopted)).toBe('adopted');
  });

  it('does not guess at a customised or unrelated file', () => {
    expect(classifyAppDelegate('')).toBe('unknown');
    expect(classifyAppDelegate('class AppDelegate: UIResponder {}')).toBe('unknown');
    // classic in spirit, but the window creation was taken out by someone
    expect(classifyAppDelegate(classic.replace('window = UIWindow(frame: UIScreen.main.bounds)', ''))).toBe('unknown');
  });
});

describe('patchAppDelegate', () => {
  it('writes the scene-based AppDelegate for a classic one', () => {
    expect(patchAppDelegate(classic)).toBe(adopted);
  });

  it('leaves an already-adopted AppDelegate exactly as it is, so a second run changes nothing', () => {
    expect(patchAppDelegate(adopted)).toBe(adopted);
    expect(patchAppDelegate(patchAppDelegate(classic))).toBe(patchAppDelegate(classic));
  });

  it('never overwrites an adopted AppDelegate that has been customised', () => {
    const customised = adopted.replace('@main', '// added by someone else\n@main');
    expect(customised).not.toBe(adopted);
    expect(patchAppDelegate(customised)).toBe(customised);
  });

  it('stops with a clear message for a file it does not recognise, instead of overwriting it', () => {
    expect(() => patchAppDelegate('class AppDelegate: UIResponder {}')).toThrow(/not the Expo SDK 57 template/);
    expect(() => patchAppDelegate('class AppDelegate: UIResponder {}')).toThrow(/ExpoReactNativeFactoryProvider/);
  });
});

describe('the Swift files', () => {
  it('the new AppDelegate conforms to the provider and no longer creates the window or starts React Native', () => {
    expect(adopted).toMatch(/class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider/);
    expect(adopted).not.toMatch(/UIWindow\(frame:/);
    expect(adopted).not.toMatch(/startReactNative/);
    expect(adopted).toMatch(/reactNativeFactory = factory/); // the scene delegate reads the factory from here
    expect(adopted).toMatch(/var window: UIWindow\?/);
  });

  it('keeps the dev-client bundle URL logic of the classic AppDelegate', () => {
    for (const keep of ['bridge.bundleURL ?? bundleURL()', 'jsBundleURL(forBundleRoot: ".expo/.virtual-metro-entry")', 'forResource: "main"'])
      expect(classic).toContain(keep);
    for (const keep of ['bridge.bundleURL ?? bundleURL()', 'jsBundleURL(forBundleRoot: ".expo/.virtual-metro-entry")', 'forResource: "main"'])
      expect(adopted).toContain(keep);
  });

  it('SceneDelegate builds on Expo\'s scene delegate and is exposed to Objective-C under the name the plist uses', () => {
    expect(sceneDelegate).toMatch(/class SceneDelegate: ExpoAppSceneDelegate/);
    expect(sceneDelegate).toMatch(/@objc\(SceneDelegate\)/);
  });
});

describe('addSceneManifest', () => {
  it('adds a single-scene manifest naming SceneDelegate in the app\'s own module', () => {
    const result = addSceneManifest({ CFBundleName: 'x' });
    expect(result.CFBundleName).toBe('x');
    expect(result.UIApplicationSceneManifest.UIApplicationSupportsMultipleScenes).toBe(false);
    const [config] = result.UIApplicationSceneManifest.UISceneConfigurations.UIWindowSceneSessionRoleApplication;
    expect(config.UISceneDelegateClassName).toBe('$(PRODUCT_MODULE_NAME).SceneDelegate');
    expect(config.UISceneConfigurationName).toBe('Default Configuration');
  });

  it('does not touch a plist that already has a scene manifest', () => {
    const existing = { UIApplicationSceneManifest: { custom: true } };
    expect(addSceneManifest(existing)).toBe(existing);
  });

  it('does not change the object it was given', () => {
    const input = { CFBundleName: 'x' };
    addSceneManifest(input);
    expect(input).toEqual({ CFBundleName: 'x' });
    expect(SCENE_MANIFEST.UIApplicationSupportsMultipleScenes).toBe(false);
  });
});
